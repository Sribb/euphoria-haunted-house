"""Generates src/art/clockmaker.ts: the Clock Tower's ghost, the Clockmaker, in three moods. 30 x 32.

Usage (from the repo root): ~/video-project/.audio-venv/bin/python scripts/art/gen_clockmaker.py
Every mood goes through the fixer (scripts/art/fixer.py) before it is written.
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from fixer import ROOT, polish  # noqa: E402
from ghostkit import W, put, shaded, ts_rows  # noqa: E402

FIXES = []


def clockmaker(base, shadow, light, outline, eye, watch=True):
    g = shaded(base, shadow, light, outline, top=6)
    # a flat workman's cap: a soft crown and a short peak out over the brow
    for y, (x0, x1) in {3: (10, 19), 4: (8, 21), 5: (7, 22), 6: (7, 22)}.items():
        for x in range(x0, x1 + 1):
            put(g, x, y, "g" if x < 15 else "O")
    for x in range(9, 14):
        put(g, x, 4, "G")           # the cap catches the light
    for x in range(5, 17):
        put(g, x, 7, "O")           # the peak
    for x in range(5, 15):
        put(g, x, 8, "K")           # its shadow
    # round brass spectacles, tired eyes behind them
    for cx in (10, 19):
        for dx, dy in [(-1, -2), (0, -2), (1, -2), (-2, -1), (2, -1), (-2, 0), (2, 0), (-2, 1), (2, 1), (-1, 2), (0, 2), (1, 2)]:
            put(g, cx + dx, 12 + dy, "G")
        for dx, dy in [(-1, -1), (0, -1), (1, -1), (-1, 1), (0, 1), (1, 1), (-1, 0), (1, 0)]:
            put(g, cx + dx, 12 + dy, "w")
        put(g, cx, 12, eye)
    for x in range(13, 17):
        put(g, x, 11, "G")          # the bridge
    # a small tired mouth and a pointed beard
    for x in range(13, 17):
        put(g, x, 17, "K")
    for x, y in [(13, 18), (14, 18), (15, 18), (16, 18), (14, 19), (15, 19)]:
        put(g, x, y, "w")
    if watch:
        # a pocket watch swinging on its chain from one raised hand
        for x, y in [(22, 15), (23, 15), (23, 16)]:
            put(g, x, y, base)
        for x, y in [(24, 16), (25, 17), (25, 18), (26, 19)]:
            put(g, x, y, "g")
        for y in range(19, 27):
            for x in range(22, 30):
                d = math.hypot(x - 26, y - 23)
                if d <= 3.3:
                    put(g, x, y, "G" if d > 2.3 else "w")
        for x, y in [(26, 21), (26, 22), (26, 23), (27, 23)]:
            put(g, x, y, "K")       # the hands, at five to midnight
        put(g, 26, 19, "y")
    return ["".join(r) for r in g]


MOODS = [("x", "X", "w", "I", "R", True), ("Q", "q", "W", "E", "K", True), ("W", "Q", "W", "T", "K", False)]
restless, calm, freed = (polish(clockmaker(*m[:5], watch=m[5]), protect="KWRy5wFG", report=FIXES) for m in MOODS)
for r in restless + calm + freed:
    assert len(r) == W

src = f'''import {{ s, shade }} from "../lib/pixel/helpers";

/**
 * The Clockmaker, the ghost who haunts the Clock Tower. He built clocks all his life and always meant to
 * start saving tomorrow. Flat cap, round brass spectacles, a pointed beard, and a pocket watch stopped
 * at five to midnight. 30 x 32, three moods that swap in place. Generated by
 * scripts/art/gen_clockmaker.py and passed through the fixer.
 */

{ts_rows("RESTLESS", restless)}
{ts_rows("CALM", calm)}
{ts_rows("FREED", freed)}
const GLOW = shade(FREED, {{ T: "W", Q: "T" }});

export const clockmakerRestless = s("clockmaker-restless", "The Clockmaker, restless", ["ghost", "boss"], "Grey, red-eyed, swinging his stopped watch.", RESTLESS);
export const clockmakerCalm = s("clockmaker-calm", "The Clockmaker, calm", ["ghost", "boss"], "Lavender, after a right answer.", CALM);
export const clockmakerFreed = s("clockmaker-freed", "The Clockmaker, freed", ["ghost", "boss"], "The watch is gone and he is at peace. Play once.", FREED, {{
  frameMs: 110,
  frames: [FREED, GLOW, FREED, GLOW, FREED],
}});

export const CLOCKMAKER_SPRITES = [clockmakerRestless, clockmakerCalm, clockmakerFreed];
'''
(ROOT / "src/art/clockmaker.ts").write_text(src)
print("fixer: grid ok on", sum(g for g, _ in FIXES), "of", len(FIXES), "moods; pixels changed:", [c for _, c in FIXES])
print("\n".join(restless))
