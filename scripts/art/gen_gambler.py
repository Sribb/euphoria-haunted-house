"""Generates src/art/gambler.ts: the Cellar's ghost, the Gambler, in three moods. 30 x 32.

Usage (from the repo root): ~/video-project/.audio-venv/bin/python scripts/art/gen_gambler.py
Every mood goes through the fixer (scripts/art/fixer.py) before it is written.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from fixer import ROOT, polish  # noqa: E402
from ghostkit import W, put, shaded, ts_rows  # noqa: E402

FIXES = []


def gambler(base, shadow, light, outline, eye, cards=True):
    g = shaded(base, shadow, light, outline, top=6)
    # a dealer's eyeshade: a band round the head and a visor jutting out over the eyes
    for x in range(7, 23):
        put(g, x, 7, "t")
        put(g, x, 8, "T" if x < 16 else "t")
    for x in range(5, 25):
        put(g, x, 9, "T" if 6 <= x <= 22 else "t")
    for x in range(6, 24):
        put(g, x, 10, "K")       # the visor's shadow across the brow
    # narrow, sly eyes and a grin with one gold tooth
    for x, y in [(9, 12), (10, 12), (11, 12), (18, 12), (19, 12), (20, 12)]:
        put(g, x, y, eye)
    for x, y in [(9, 11), (20, 11)]:
        put(g, x, y, "K")
    for x in range(11, 19):
        put(g, x, 16, "K")
    for x, y in [(10, 15), (19, 15)]:
        put(g, x, y, "K")         # the grin's upturned corners
    put(g, 15, 16, "G")
    put(g, 13, 17, "K"); put(g, 14, 17, "K"); put(g, 15, 17, "K"); put(g, 16, 17, "K")
    if cards:
        # a fan of three playing cards held out to the right
        for i, (cx, cy) in enumerate([(23, 15), (25, 14), (27, 15)]):
            for y in range(cy, cy + 6):
                for x in range(cx, cx + 3):
                    put(g, x, y, "W")
            for y in range(cy, cy + 6):
                put(g, cx + 3, y, "x")
            put(g, cx + 1, cy + 2, "R" if i != 1 else "K")
        for x, y in [(22, 18), (23, 19), (22, 19)]:
            put(g, x, y, base)    # the hand holding them
    return ["".join(r) for r in g]


MOODS = [("x", "X", "w", "I", "R", True), ("Q", "q", "W", "E", "K", True), ("W", "Q", "W", "T", "K", False)]
restless, calm, freed = (polish(gambler(*m[:5], cards=m[5]), protect="KWRy5wFG", report=FIXES) for m in MOODS)


def add_dice(rows):
    g = [list(r) for r in rows]
    for ox, oy in [(1, 18), (3, 22)]:
        for y in range(oy, oy + 3):
            for x in range(ox, ox + 3):
                g[y][x] = "w"
        g[oy + 1][ox + 1] = "K"
        for y in range(oy, oy + 3):
            if g[y][ox + 3] == ".":
                g[y][ox + 3] = "D"   # a shadowed side so they read as cubes
    return ["".join(r) for r in g]


restless, calm = add_dice(restless), add_dice(calm)
for r in restless + calm + freed:
    assert len(r) == W

src = f'''import {{ s, shade }} from "../lib/pixel/helpers";

/**
 * The Gambler, the ghost who haunts the Cellar. He put everything on one bet and lost it in one bad year.
 * Dealer's visor, a sly gold-toothed grin, a fan of cards and two dice. 30 x 32, three moods that swap in
 * place. Generated by scripts/art/gen_gambler.py and passed through the fixer.
 */

{ts_rows("RESTLESS", restless)}
{ts_rows("CALM", calm)}
{ts_rows("FREED", freed)}
const GLOW = shade(FREED, {{ T: "W", Q: "T" }});

export const gamblerRestless = s("gambler-restless", "The Gambler, restless", ["ghost", "boss"], "Grey, red-eyed, holding his cards.", RESTLESS);
export const gamblerCalm = s("gambler-calm", "The Gambler, calm", ["ghost", "boss"], "Lavender, after a right answer.", CALM);
export const gamblerFreed = s("gambler-freed", "The Gambler, freed", ["ghost", "boss"], "The cards are gone and he is smiling. Play once.", FREED, {{
  frameMs: 110,
  frames: [FREED, GLOW, FREED, GLOW, FREED],
}});

export const GAMBLER_SPRITES = [gamblerRestless, gamblerCalm, gamblerFreed];
'''
(ROOT / "src/art/gambler.ts").write_text(src)
print("fixer: grid ok on", sum(g for g, _ in FIXES), "of", len(FIXES), "moods; pixels changed:", [c for _, c in FIXES])
print("\n".join(restless))
