"""Generates src/art/duchess.ts: the Portrait Gallery's ghost, the Duchess, in three moods. 30 x 32.

Usage (from the repo root): ~/video-project/.audio-venv/bin/python scripts/art/gen_duchess.py
Every mood goes through the fixer (scripts/art/fixer.py) before it is written.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from fixer import ROOT, polish  # noqa: E402
from ghostkit import W, put, shaded, ts_rows  # noqa: E402

FIXES = []


def duchess(base, shadow, light, outline, eye, fan=True):
    g = shaded(base, shadow, light, outline, top=8)
    # a tall powdered updo, piled in three tiers, with a gold tiara at its foot
    tiers = {0: (12, 17), 1: (11, 18), 2: (10, 19), 3: (10, 19), 4: (9, 20), 5: (9, 20), 6: (8, 21), 7: (8, 21), 8: (8, 21)}
    for y, (x0, x1) in tiers.items():
        for x in range(x0, x1 + 1):
            edge = x in (x0, x1) or y == 0
            put(g, x, y, "X" if edge else ("w" if x < 14 else "x"))
    for x, y in [(13, 2), (15, 4), (12, 5), (17, 6), (14, 7)]:
        put(g, x, y, "X")          # curls
    for x in range(8, 22):
        put(g, x, 9, "G")
    for x in (10, 14, 15, 19):
        put(g, x, 8, "y")          # the tiara's points
    put(g, 14, 9, "R"); put(g, 15, 9, "R")
    # heavy-lidded eyes, lashes, a beauty mark, a small pursed mouth
    for cx in (10, 19):
        put(g, cx - 1, 12, "K"); put(g, cx, 12, "K"); put(g, cx + 1, 12, "K")
        put(g, cx, 13, eye); put(g, cx + 1, 13, eye)
        put(g, cx + 2, 11, "K")
    put(g, 20, 15, "K")
    for x, y in [(14, 16), (15, 16)]:
        put(g, x, y, "R")
    put(g, 13, 16, "K"); put(g, 16, 16, "K")
    # a pearl necklace in two strands
    for x in range(9, 21, 2):
        put(g, x, 19, "W")
    for x in range(10, 20, 2):
        put(g, x, 20, "W")
    put(g, 14, 21, "G"); put(g, 15, 21, "G")
    if fan:
        # an open fan held out to one side
        for x, y in [(22, 17), (23, 17), (23, 18)]:
            put(g, x, y, base)
        ribs = [(24, 18, 29, 12), (24, 18, 29, 15), (24, 18, 29, 18), (24, 18, 28, 21), (24, 18, 26, 23)]
        for x0, y0, x1, y1 in ribs:
            n = max(abs(x1 - x0), abs(y1 - y0))
            for i in range(n + 1):
                put(g, round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n), "f")
        for x, y in [(26, 14), (27, 15), (27, 16), (27, 17), (27, 19), (26, 20), (25, 21), (28, 13), (28, 14), (28, 16), (28, 17), (28, 19), (28, 20), (27, 21), (26, 22)]:
            put(g, x, y, "F")
        put(g, 24, 18, "G")
    return ["".join(r) for r in g]


MOODS = [("x", "X", "w", "I", "R", True), ("Q", "q", "W", "E", "K", True), ("W", "Q", "W", "T", "K", False)]
restless, calm, freed = (polish(duchess(*m[:5], fan=m[5]), protect="KWRy5wFGf", report=FIXES) for m in MOODS)
for r in restless + calm + freed:
    assert len(r) == W

src = f'''import {{ s, shade }} from "../lib/pixel/helpers";

/**
 * The Duchess, the ghost who haunts the Portrait Gallery. She lent a fortune to one company and bought
 * a piece of another, and never learned which of the two gets paid first. A tall powdered updo, a gold
 * tiara, pearls, and a fan. 30 x 32, three moods that swap in place. Generated by
 * scripts/art/gen_duchess.py and passed through the fixer.
 */

{ts_rows("RESTLESS", restless)}
{ts_rows("CALM", calm)}
{ts_rows("FREED", freed)}
const GLOW = shade(FREED, {{ T: "W", Q: "T" }});

export const duchessRestless = s("duchess-restless", "The Duchess, restless", ["ghost", "boss"], "Grey, red-eyed, snapping her fan.", RESTLESS);
export const duchessCalm = s("duchess-calm", "The Duchess, calm", ["ghost", "boss"], "Lavender, after a right answer.", CALM);
export const duchessFreed = s("duchess-freed", "The Duchess, freed", ["ghost", "boss"], "The fan is folded away and she is at peace. Play once.", FREED, {{
  frameMs: 110,
  frames: [FREED, GLOW, FREED, GLOW, FREED],
}});

export const DUCHESS_SPRITES = [duchessRestless, duchessCalm, duchessFreed];
'''
(ROOT / "src/art/duchess.ts").write_text(src)
print("fixer: grid ok on", sum(g for g, _ in FIXES), "of", len(FIXES), "moods; pixels changed:", [c for _, c in FIXES])
print("\n".join(calm))
