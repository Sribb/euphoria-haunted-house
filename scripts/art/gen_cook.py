"""Generates src/art/cook.ts: the Kitchen's ghost, the Cook, in three moods. 30 x 32.

Usage (from the repo root): ~/video-project/.audio-venv/bin/python scripts/art/gen_cook.py
Every mood goes through the fixer (scripts/art/fixer.py) before it is written.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from fixer import ROOT, polish  # noqa: E402
from ghostkit import W, put, shaded, ts_rows  # noqa: E402

FIXES = []


def cook(base, shadow, light, outline, eye, basket=True):
    g = shaded(base, shadow, light, outline, top=9)
    # a tall chef's toque: a puffed top over a straight band
    puff = {0: (10, 19), 1: (8, 21), 2: (7, 22), 3: (7, 22), 4: (8, 21)}
    for y, (x0, x1) in puff.items():
        for x in range(x0, x1 + 1):
            put(g, x, y, "D" if x in (x0, x1) or y == 0 else ("W" if x < 14 else "w"))
    for x in (11, 15, 19):
        put(g, x, 3, "x"); put(g, x, 4, "x")      # pleats
    for y in range(5, 10):
        for x in range(9, 21):
            put(g, x, y, "D" if x in (9, 20) else ("W" if x < 13 else "w"))
    for x in range(9, 21):
        put(g, x, 9, "x")
    # small eyes, round cheeks, and a grand curled mustache
    for cx in (11, 18):
        put(g, cx, 12, eye); put(g, cx, 13, eye)
    put(g, 9, 14, "F"); put(g, 10, 14, "F"); put(g, 19, 14, "F"); put(g, 20, 14, "F")
    for x, y in [(12, 16), (13, 15), (14, 15), (15, 15), (16, 15), (17, 16), (11, 16), (18, 16), (10, 15), (19, 15), (10, 14), (19, 14)]:
        put(g, x, y, "K")
    put(g, 14, 17, "K"); put(g, 15, 17, "K")
    # an apron tied at the neck
    for y in range(19, 25):
        for x in range(11, 19):
            if g[y][x] not in (".", outline):
                put(g, x, y, "w" if x < 16 else "x")
    for x in range(10, 20):
        put(g, x, 19, "x")
    if basket:
        # one basket, every egg he owns in it, held out proudly
        for x, y in [(22, 18), (23, 18), (23, 19)]:
            put(g, x, y, base)
        for y, (x0, x1) in {21: (22, 29), 22: (22, 29), 23: (23, 28), 24: (23, 28), 25: (24, 27)}.items():
            for x in range(x0, x1 + 1):
                put(g, x, y, "O" if x in (x0, x1) or y == 25 else ("G" if (x + y) % 2 else "g"))
        for x in range(22, 30):
            put(g, x, 20, "O")
        for x, y in [(23, 19), (24, 18), (24, 19), (26, 18), (26, 19), (27, 19), (28, 19), (25, 17), (26, 17)]:
            put(g, x, y, "W")       # the eggs
        put(g, 25, 19, "x"); put(g, 27, 18, "x")
        for x, y in [(24, 14), (25, 13), (26, 13), (27, 14), (28, 16), (23, 16)]:
            put(g, x, y, "O")       # the handle
    return ["".join(r) for r in g]


MOODS = [("x", "X", "w", "I", "R", True), ("Q", "q", "W", "E", "K", True), ("W", "Q", "W", "T", "K", False)]
restless, calm, freed = (polish(cook(*m[:5], basket=m[5]), protect="KWRy5wFG", report=FIXES) for m in MOODS)
for r in restless + calm + freed:
    assert len(r) == W

src = f'''import {{ s, shade }} from "../lib/pixel/helpers";

/**
 * The Cook, the ghost who haunts the Kitchen. He carried every egg he owned in one basket, and one slip
 * took them all. A tall toque, a grand curled mustache, an apron, and that one basket. 30 x 32, three
 * moods that swap in place. Generated by scripts/art/gen_cook.py and passed through the fixer.
 */

{ts_rows("RESTLESS", restless)}
{ts_rows("CALM", calm)}
{ts_rows("FREED", freed)}
const GLOW = shade(FREED, {{ T: "W", Q: "T" }});

export const cookRestless = s("cook-restless", "The Cook, restless", ["ghost", "boss"], "Grey, red-eyed, gripping his one basket.", RESTLESS);
export const cookCalm = s("cook-calm", "The Cook, calm", ["ghost", "boss"], "Lavender, after a right answer.", CALM);
export const cookFreed = s("cook-freed", "The Cook, freed", ["ghost", "boss"], "The basket is set down and he is at peace. Play once.", FREED, {{
  frameMs: 110,
  frames: [FREED, GLOW, FREED, GLOW, FREED],
}});

export const COOK_SPRITES = [cookRestless, cookCalm, cookFreed];
'''
(ROOT / "src/art/cook.ts").write_text(src)
print("fixer: grid ok on", sum(g for g, _ in FIXES), "of", len(FIXES), "moods; pixels changed:", [c for _, c in FIXES])
print("\n".join(calm))
